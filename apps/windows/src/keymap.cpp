ScanResult usage_to_scan(std::uint16_t usage) {
    if (usage == 0x48) return {KeyMapStatus::ok, {0x45, false, true}};
    for (const auto& entry : entries) if (entry.usage == usage)
        return {KeyMapStatus::ok, {entry.scan, entry.extended, false}};
    return {KeyMapStatus::unsupported_usage, {0, false, false}};
}
UsageResult scan_to_usage(ScanCode scan) {
    if (!scan.code || (scan.extended && scan.e1)) return {KeyMapStatus::invalid_scan, 0};
    if (scan.e1) return scan.code == 0x45 ? UsageResult{KeyMapStatus::ok, 0x48}
                                         : UsageResult{KeyMapStatus::unknown_scan, 0};
    // Legacy key messages may expose NumLock as E0 45 rather than 00 45.
    if (scan.extended && scan.code == 0x45) return {KeyMapStatus::ok, 0x53};
    for (const auto& entry : entries) if (entry.scan == scan.code && entry.extended == scan.extended)
        return {KeyMapStatus::ok, entry.usage};
    return {KeyMapStatus::unknown_scan, 0};
}

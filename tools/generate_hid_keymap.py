#!/usr/bin/env python3
"""Generate v2 Mac/Harmony physical-key tables from auditable JSON sources."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
HID = ROOT / 'protocol/v2-hid-keymap.json'
V1 = ROOT / 'protocol/keymap.json'
SWIFT = ROOT / 'apps/macos/Sources/HIDKeymap.swift'
HEADER = ROOT / 'apps/harmonyos/entry/src/main/cpp/generated/hid_keymap.h'


def outputs():
    hid_bytes, v1_bytes = HID.read_bytes(), V1.read_bytes()
    source, v1 = json.loads(hid_bytes), json.loads(v1_bytes)
    assert source['version'] == 1 and v1['version'] == 1
    by_symbol = {item['mac_symbol']: item for item in v1['keys']}
    assert len(by_symbol) == len(v1['keys'])
    entries = source['keys']
    assert len({x['mac_symbol'] for x in entries}) == len(entries)
    assert len({x['hid_usage'] for x in entries}) == len(entries)
    assert all(x['mac_symbol'] in by_symbol and isinstance(x['hid_usage'], int) and 1 <= x['hid_usage'] <= 0xe7 for x in entries)
    digest = hashlib.sha256(hid_bytes).hexdigest()
    rows = '\n'.join(f'            "{x["mac_symbol"]}": 0x{x["hid_usage"]:02x},' for x in entries)
    swift = '''// Generated by tools/generate_hid_keymap.py from protocol/v2-hid-keymap.json; do not edit.
import Foundation

/// Physical USB HID keyboard-page identities; target IME/layout handles text.
struct HIDKeymap {
    let macToHID: [UInt16: UInt16]
    let hidToMac: [UInt16: UInt16]
    init(keymap: Keymap) throws {
        let symbols: [String: UInt16] = [
''' + rows + '''
        ]
        var forward: [UInt16: UInt16] = [:], reverse: [UInt16: UInt16] = [:]
        for key in keymap.keys {
            guard let usage = symbols[key.mac_symbol] else { continue }
            guard forward[key.mac] == nil && reverse[usage] == nil else { throw WireError.invalid("Duplicate v2 physical keyboard mapping") }
            forward[key.mac] = usage; reverse[usage] = key.mac
        }
        macToHID = forward; hidToMac = reverse
    }
}
'''
    table = [-1] * 0xe8
    for entry in entries:
        target = by_symbol[entry['mac_symbol']]['harmony']
        if target is not None:
            table[entry['hid_usage']] = target
    chunks = ',\n'.join('    ' + ', '.join(str(x) for x in table[i:i+8]) for i in range(0, len(table), 8))
    header = f'''// Generated by tools/generate_hid_keymap.py; do not edit.
// v2-hid-keymap.json SHA256: {digest}
// keymap.json SHA256: {hashlib.sha256(v1_bytes).hexdigest()}
#pragma once
#include <cstdint>
namespace hop {{
inline constexpr int32_t kHopHidKeymap[0xe8] = {{
{chunks}
}};
inline constexpr int32_t MapHidKey(uint16_t usage) {{
    return usage < 0xe8 ? kHopHidKeymap[usage] : -1;
}}
}} // namespace hop
'''
    return {SWIFT: swift, HEADER: header}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, content in outputs().items():
        if args.check:
            if not path.is_file() or path.read_text() != content:
                raise SystemExit(f'Stale generated file: {path.relative_to(ROOT)}')
        else:
            path.write_text(content)
        print(('checked ' if args.check else 'generated ') + str(path.relative_to(ROOT)))


if __name__ == '__main__':
    main()

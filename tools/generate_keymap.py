#!/usr/bin/env python3
"""Generate native resources/docs from protocol/keymap.json (Python standard library)."""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'protocol/keymap.json'
HEADER = ROOT / 'apps/harmonyos/entry/src/main/cpp/generated/keymap.h'
DOCUMENT = ROOT / 'docs/KEYMAP.md'


def load():
    raw = SOURCE.read_bytes()
    data = json.loads(raw)
    entries = data['keys']
    assert data['version'] == 1
    codes = [e['mac'] for e in entries]
    assert len(codes) == len(set(codes)), 'duplicate Mac keycode'
    assert all(0 <= c < 128 for c in codes)
    assert all(e['status'] in ('mapped', 'conditional', 'unsupported') for e in entries)
    assert all((e['harmony'] is None) == (e['status'] == 'unsupported') for e in entries)
    assert all(e['harmony'] is None or 0 <= e['harmony'] < 65536 for e in entries)
    return data, hashlib.sha256(raw).hexdigest()


def render():
    data, digest = load()
    keys = sorted(data['keys'], key=lambda e: e['mac'])
    table = {e['mac']: e['harmony'] if e['harmony'] is not None else -1 for e in keys}
    values = ',\n'.join('    ' + ', '.join(str(table.get(i, -1)) for i in range(start, start + 8)) for start in range(0, 128, 8))
    header = f'''// Generated by tools/generate_keymap.py; DO NOT EDIT.
// protocol/keymap.json SHA256: {digest}
#pragma once
#include <cstdint>
namespace hop {{
inline constexpr int32_t kHopKeymap[128] = {{
{values}
}};
inline constexpr int32_t MapMacKey(uint16_t key) {{
    return key < 128 ? kHopKeymap[key] : -1;
}}
}} // namespace hop
'''
    lines = ['# Mac ↔ HarmonyOS 物理键位映射', '', '> Generated by `python3 tools/generate_keymap.py`. Do not edit this table directly.', '',
             f'Source: `protocol/keymap.json` · SHA-256 `{digest}`', '',
             '## 规则与限制', '',
             '- 以物理键位传输，不传字符；键盘布局和输入法由接收端系统决定。Cmd 映射 Meta，不自动替换为 Ctrl。',
             '- 左/右 Shift、Ctrl、Option、Cmd 分开编码；modifier bits 0..8 见协议。CapsLock 使用锁定状态，离开时不遗留物理按下。',
             '- `mapped` 表示有 SDK 中的明确目标键码，不等于已通过真机验证；所有键位仍须按验收清单实测。',
             '- `conditional` 表示存在目标码但 Mac 的系统保留/媒体事件捕获可能受硬件与系统设置影响。',
             '- `unsupported` 不猜目标码，接收端丢弃但不得遗留按下状态；Fn/亮度与厂商媒体键不承诺捕获。',
             '- Keypad Clear 不等于 NumLock，JIS 英数/かな不等于简单的切换假名事件，因此未作不可靠替换。',
             '- ISO Section 对应额外 ISO 物理键（102ND），JIS underscore 对应 RO、Yen 对应 YEN；字形依目标布局。',
             '', '## SDK 依据', '',
             f'- macOS: `{data["sources"]["macos"]}` (`kVK_*`).',
             f'- HarmonyOS: `{data["sources"]["harmonyos"]}` (`KEYCODE_*`); values checked against installed SDK.', '',
             '## 全部已定义 Mac 键位', '',
             '| Mac 十进制 / hex | Mac symbol | Harmony code | Harmony symbol | 状态 / 说明 |',
             '|---|---|---:|---|---|']
    for e in keys:
        lines.append(f'| {e["mac"]} / 0x{e["mac"]:02X} | {e["mac_symbol"]} | {e["harmony"] if e["harmony"] is not None else "—"} | {e["harmony_symbol"] or "—"} | {e["status"]}: {e["notes"]} |')
    lines += ['', '## 不在标准 kVK 表内的硬件键', '',
              '亮度、播放/暂停、快进/后退、电源、Touch ID、厂商键等常经 NX_SYSDEFINED 或系统固件处理。v1 不编造 Mac 虚拟键码，也不声称全硬件键支持。F1–F20 的普通功能键事件按上表处理（可能需按 Fn 或修改系统功能键设置）。', '']
    return {HEADER: header, DOCUMENT: '\n'.join(lines)}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='fail if generated files are stale')
    args = parser.parse_args()
    for path, text in render().items():
        if args.check:
            if not path.is_file() or path.read_text() != text:
                raise SystemExit(f'Stale generated file: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
        print(('checked ' if args.check else 'generated ') + str(path.relative_to(ROOT)))


if __name__ == '__main__':
    main()
